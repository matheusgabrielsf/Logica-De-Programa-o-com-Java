public class ExpressoesComparativas {
    public static void main(String[] args) {
        int pao = 5;
        int queijo = 10;

        System.out.println("Pão é maior que queijo? " + (pao > queijo));
        System.out.println("Pão é menor que queijo? " + (pao < queijo));
        System.out.println("Pão é igual a queijo? " + (pao == queijo    )); 
        System.out.println("Pão é diferente de queijo? " + (pao != queijo));
        System.out.println("Pão é maior ou igual a queijo? " + (pao >= queijo));
        System.out.println("Pão é menor ou igual a queijo? " + (pao <= queijo));
    }
    
}
