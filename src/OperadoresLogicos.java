public class OperadoresLogicos {
    public static void main(String[] args) {
        boolean x = true;
        boolean y = false;

        System.out.println("x && y: " + (x && y)); // Operador lógico E
        System.out.println("x || y: " + (x || y)); // Operador lógico OU
        System.out.println("x ^ y: " + (x ^ y)); // Operador lógico OU exclusivo
        System.out.println("!x: " + (!x)); // Operador lógico de negação
    }
}
